CREATE FUNCTION public.recalculate_meal_plan_totals(p_meal_plan_id integer) RETURNS void
    LANGUAGE plpgsql
    AS $$
BEGIN
    UPDATE meal_plans mp
    SET
        total_calories = COALESCE(x.total_calories, 0),
        total_protein = COALESCE(x.total_protein, 0),
        total_fat = COALESCE(x.total_fat, 0),
        total_carbohydrates = COALESCE(x.total_carbohydrates, 0)
    FROM (
        SELECT
            mpi.meal_plan_id,
            ROUND(SUM(rn.calories_per_serving * mpi.servings_multiplier), 2) AS total_calories,
            ROUND(SUM(rn.protein_per_serving_g * mpi.servings_multiplier), 2) AS total_protein,
            ROUND(SUM(rn.fat_per_serving_g * mpi.servings_multiplier), 2) AS total_fat,
            ROUND(SUM(rn.carbohydrates_per_serving_g * mpi.servings_multiplier), 2) AS total_carbohydrates
        FROM meal_plan_items mpi
        JOIN recipe_nutrition rn
            ON rn.id = mpi.recipe_id
        WHERE mpi.meal_plan_id = p_meal_plan_id
        GROUP BY mpi.meal_plan_id
    ) x
    WHERE mp.id = x.meal_plan_id;

    IF NOT FOUND THEN
        UPDATE meal_plans
        SET
            total_calories = 0,
            total_protein = 0,
            total_fat = 0,
            total_carbohydrates = 0
        WHERE id = p_meal_plan_id;
    END IF;
END;
$$;


